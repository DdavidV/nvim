defmodule Mix.Tasks.Compile.NvimApi do
  use Mix.Task.Compiler

  @impl true
  def run(_args) do
    Mix.shell().info("Compiling Neovim API...")
    case Application.ensure_all_started(:nvim_rpc) do
      {:ok, _} ->
        :ok
      {:error, reason} ->
        Mix.raise("Cannot start nvim_rpc: #{inspect(reason)}")
    end
    module =
      case :nvim_rpc.ensure_api_bindings() do
        {:ok, module} ->
          Mix.shell().info("Neovim bindings generated")
          module
        {:error, reason} ->
          Mix.raise("Cannot generate nvim bindings: #{inspect(reason)}")
      end

    case Code.ensure_loaded(module) do
      {:module, ^module} ->
        :ok
      {:error, reason} ->
        Mix.raise("Generated bindings module cannot be loaded: #{inspect(reason)}")
    end

    path = Path.expand("lib/nvim/api.ex")
    exports = exports(module)

    generate_api(path, exports)

    Mix.shell().info("Generated #{length(exports)} Neovim API functions.")
  end

  defp exports(module) do
    module.module_info(:exports)
    |> Enum.reject(fn
      {name, _arity} when name in [:module_info, :behaviour_info] -> true
      {name, 0} when name in [:api_hash, :api_version] -> true
      {:type_id, 1} -> true
      {:type_name, 1} -> true
      _ -> false
    end)
    |> Enum.uniq()
    |> Enum.sort()
  end

  defp generate_api(path, exports) do
    File.mkdir_p!(Path.dirname(path))
    functions =
      Enum.map_join(exports, "\n\n", fn {name, arity} ->
        generate_function(name, arity)
      end)

    source = """
    # Generated by #{__MODULE__}. Do not edit manually.

    defmodule Nvim.API do
      @moduledoc \"\"\"
      Automatically generated wrappers for the Neovim RPC API.
      Calls are forwarded to `Nvim.api/3`.
      \"\"\"

    #{indent(functions, 2)}
    end
    """

    File.write!(path, source)
    {:ok, path}
  end

  defp generate_function(name, erlang_arity) do
    # Erlang functions accept RequestId as their first argument which will be added by the host.
    api_arity = erlang_arity - 1
    args = for index <- 1..max(api_arity, 1), api_arity > 0, do: "arg#{index}"

    args =
      if api_arity == 0 do
        []
      else
        args
      end

    function_name = Atom.to_string(name)
    params = Enum.join(args, ", ")
    list = Enum.join(args, ", ")

    signature =
      if api_arity == 0 do
        "call_opts \\\\ []"
      else
        "#{params}, call_opts \\\\ []"
      end

    """
    @doc "Calls `#{function_name}` through the Neovim RPC host."
    def #{function_name}(#{signature}) do
      timeout = Keyword.get(call_opts, :timeout, 5000)
      Nvim.api(:#{function_name}, [#{list}], timeout)
    end
    """
  end

  defp indent(source, spaces) do
    prefix = String.duplicate(" ", spaces)

    source
    |> String.split("\n")
    |> Enum.map_join("\n", fn
      "" -> ""
      line -> prefix <> line
    end)
  end

end
